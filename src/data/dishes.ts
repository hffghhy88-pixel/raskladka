import type { ColdProcess, Dish, DishCategory, DishLine, HotProcess, LineGroup, Unit } from "../types/models";

let lineSeq = 0;

function L(
  productId: string,
  quantity: number,
  unit: Unit,
  cold: ColdProcess = "none",
  hot: HotProcess = "none",
  extra: Partial<DishLine> = {},
): DishLine {
  lineSeq += 1;
  return {
    id: `ln_${productId}_${lineSeq}`,
    productId,
    quantity,
    unit,
    cold,
    hot,
    group: (extra.group as LineGroup) ?? "main",
    optional: extra.optional ?? false,
    excludeFromYield: extra.excludeFromYield ?? false,
    excludeFromShopping: extra.excludeFromShopping ?? false,
    note: extra.note,
    coldLossOverride: extra.coldLossOverride,
    hotYieldOverride: extra.hotYieldOverride,
  };
}

function D(
  id: string,
  name: string,
  category: DishCategory,
  target: number,
  lines: DishLine[],
  extra: Partial<Dish> = {},
): Dish {
  return {
    id,
    name,
    category,
    basePortions: extra.basePortions ?? 10,
    targetPortionG: target,
    lines,
    steps: extra.steps ?? [],
    description: extra.description,
    cookTimeMin: extra.cookTimeMin ?? 30,
    prepTimeMin: extra.prepTimeMin ?? 15,
    difficulty: extra.difficulty ?? 2,
    tags: extra.tags ?? [],
    cuisine: extra.cuisine ?? "русская",
    finishingLossPercent: extra.finishingLossPercent ?? 2,
    evaporationG: extra.evaporationG ?? 0,
    archived: false,
  };
}

